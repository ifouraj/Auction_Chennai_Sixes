function normalPlayer(
  id: string,
  name: string,
  country: string,
  age: number,
  description: string,
  batting: number,
  bowling: number,
  wicketKeeping: number,
  leadership: number,
  overall: number,
  basePrice: number,
  imageRef?: string,
): Player {
  return {
    id,
    name,
    country,
    age,
    description,
    batting,
    bowling,
    wicketKeeping,
    leadership,
    overall,
    basePrice,
    kind: 'NORMAL',
    ...(imageRef === undefined ? {} : { imageRef }),
  }
}

